#!/usr/bin/env python3
"""Measures each container on its own and judges the registry's choices from the results.

    record.py record --binary build/benchmark_comparisons    measure the missing and stale cells (all with --all)
    record.py coverage --binary build/benchmark_comparisons  the binary registers exactly the cells (a test)
    record.py check                                          every cell measured and current; every choice holds
    record.py doc [--check]                                  write (or check) the generated part of BENCHMARKS.md

What is measured (benchmarks/requests.json): each container on each shape of element, its whole lifecycle at three
sizes, every operation it offers timed in turn. A cell is one such experiment at one size; its result is the median
time per operation (ns), with a fingerprint of the sources it measured (the container's headers with every urd
header they include, the Store's facets, the benchmark code). A result whose fingerprint no longer matches is stale.
Results are per machine (benchmarks/results/<machine>.json).

What is judged, from data only: for each request, the container the registry chooses against every other that serves
it, on the operations the request's Store offers. An other that gives a costly guarantee the request did not ask for
and the chosen one does not give (its "uninvited" guarantees, benchmarks/requests.json, are no subset of the chosen
one's) is no fair alternative: a Store gives no such guarantee unasked, however fast, so it is not compared. The others
are compared by their costs (share/urd/complexity.json):
- settled: the chosen one grows slower on some operation and faster on none;
- wrong_order: the other grows slower on some and faster on none, and takes no more memory: the registry is wrong;
- measure: they grow alike, each grows slower somewhere, or the request says small. The tie is broken asymptotically:
  at the largest size measured, the chosen one's lifecycle (the sum of its operations' times per element) may exceed
  the other's by at most the tolerance or the floor, whichever is larger. Losing at a smaller size only is reported,
  not failed: the registry picks one container for every size, and the one ahead as n grows is the better pick.
Nothing is measured per comparison, and nothing is excused in writing: a comparison reads two containers' results.
"""

import argparse
import concurrent.futures
import datetime
import hashlib
import json
import math
import os
import platform
import queue
import random
import resource
import re
import statistics
import subprocess
import sys
import threading
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REQUESTS = ROOT / "benchmarks" / "requests.json"
TOLERANCE = 0.1  # a measured choice may be this much slower...
FLOOR = 5.0  # ...or this many ns per element, whichever is larger: below it, the difference is a few instructions
RESULTS = ROOT / "benchmarks" / "results"
COMPLEXITY = ROOT / "share" / "urd" / "complexity.json"
DOC = ROOT / "docs" / "BENCHMARKS.md"
BEGIN = "<!-- generated by benchmarks/record.py doc: edit outside this block -->"
END = "<!-- end of the generated block -->"


def requests() -> dict:
    """benchmarks/requests.json."""
    return json.loads(REQUESTS.read_text())


def cells() -> list[str]:
    """The cells: each experiment at each of its sizes."""
    return [f"{name}/{size}" for name, experiment in requests()["experiments"].items() for size in experiment["sizes"]]


def container_of(cell: str) -> str:
    """The container a cell measures: the part before its first slash."""
    return cell.split("/", 1)[0]


def closure(start: list[Path]) -> list[Path]:
    """The files, and every urd header they include, transitively."""
    seen: set[Path] = set()
    todo = list(start)
    while todo:
        path = todo.pop()
        if path in seen or not path.exists():
            continue
        seen.add(path)
        for included in re.findall(r'#include "(urd/[^"]+)"', path.read_text()):
            todo.append(ROOT / "include" / included)
    return sorted(seen)


def code_of(path: Path) -> str:
    """A source as measured: without comments and whitespace, so rewording or reformatting it stales no result."""
    text = re.sub(r"//[^\n]*|/\*.*?\*/", "", path.read_text(), flags=re.DOTALL)
    return re.sub(r"\s+", "", text)


def fingerprints() -> dict[str, str]:
    """For each container, the hash of the sources its cells measure: its headers, the Store, the benchmark."""
    common = [*sorted((ROOT / "include" / "urd" / "store").glob("*.hpp")), ROOT / "include" / "urd" / "store.hpp",
              *(ROOT / "benchmarks" / name for name in ("experiment.cpp", "lifecycle.hpp", "cells.hpp")),
              ROOT / "docs" / "SOURCES.json"]
    result = {}
    for container, headers in requests()["headers"].items():
        digest = hashlib.sha256()
        for path in closure(common + [ROOT / "include" / header for header in headers]):
            digest.update(str(path.relative_to(ROOT)).encode())
            digest.update(code_of(path).encode())
        result[container] = digest.hexdigest()[:16]
    return result


def results_path(machine: str | None) -> Path:
    """The results file of `machine`, by default this one's."""
    return RESULTS / f"{machine or platform.node()}.json"


def load_results(path: Path) -> dict:
    """A results file, or an empty one."""
    if path.exists():
        return json.loads(path.read_text())
    return {"machine": path.stem, "cells": {}}


def stale_or_missing(results: dict, prints: dict[str, str]) -> list[str]:
    """The cells without a result, or whose result measured other sources."""
    held = results["cells"]
    return [c for c in cells() if c not in held or held[c]["fingerprint"] != prints[container_of(c)]]


# The address space a cell may take: past it the cell fails (recorded), instead of the machine running out of memory.
memory_limit = 8 << 30

def complexity() -> dict:
    """share/urd/complexity.json: the operations, the growths in order, each quantity's scale, each container's costs."""
    return json.loads(COMPLEXITY.read_text())


def escaped(text: str) -> str:
    """Text as a literal for Google Benchmark's filter (std::regex, which rejects Python's escapes of '-' and ',')."""
    return re.sub(r"([.^$|?*+()\[\]{}\\])", r"\\\1", text)


def measure(binary: Path, cell: str, cpu: int | None, arguments: argparse.Namespace) -> dict | None:
    """The median time of each operation of one cell's lifecycle (ns), or None where it ran past the time limit."""
    pattern = "^" + escaped(cell) + "(/iterations:[0-9]+)?$"
    command = [str(binary), f"--benchmark_filter={pattern}", "--benchmark_repetitions=3", "--benchmark_format=json"]
    if cpu is not None:
        command = ["taskset", "-c", str(cpu), *command]
    try:
        done = subprocess.run(command, check=True, capture_output=True, text=True, timeout=arguments.limit,
                              preexec_fn=lambda: resource.setrlimit(resource.RLIMIT_AS, (memory_limit, memory_limit)))
    except subprocess.TimeoutExpired:
        return None
    except subprocess.CalledProcessError as failure:
        reason = (failure.stderr or "").strip()[-300:] or f"exit {failure.returncode}"
        return {"failed": "out of memory (8 GB)" if "bad_alloc" in reason else reason}
    runs = [r for r in json.loads(done.stdout)["benchmarks"] if r.get("run_type") == "iteration" and not r.get("error_occurred")]
    if not runs:
        raise RuntimeError(f"{cell}: no run (" + done.stderr.strip()[:200] + ")")
    return {op: round(statistics.median(r[op] for r in runs), 3) for op in complexity()["operations"] if op in runs[0]}


def record(arguments: argparse.Namespace) -> int:
    """Measures the missing and stale cells (all with --all), one process each in shuffled order, and merges them in.

    With --cpu a list (2,4,6), one cell runs on each CPU at a time: choose one hyperthread per core of one kind (all
    performance cores), so every cell runs alike. Every cell runs under a time limit: one that does not finish is
    recorded as timed out (`check` reports it), so a pathological cell cannot stall the recording. The results are
    written after every cell.
    """
    path = results_path(arguments.machine)
    results = load_results(path)
    prints = fingerprints()
    wanted = cells() if arguments.all else stale_or_missing(results, prints)
    random.Random(42).shuffle(wanted)
    print(f"measuring {len(wanted)} cells, at most {arguments.limit} s each")
    results["compiler"] = arguments.compiler
    model = re.search(r"model name\s*:\s*(.+)", Path("/proc/cpuinfo").read_text()) if Path("/proc/cpuinfo").exists() else None
    results["context"] = {"host": platform.node(), "cpu": model.group(1) if model else platform.processor(), "cpus": os.cpu_count()}
    RESULTS.mkdir(exist_ok=True)
    today = datetime.date.today().isoformat()
    cpus: queue.Queue[int | None] = queue.Queue()
    for cpu in [int(each) for each in arguments.cpu.split(",")] if arguments.cpu else [None]:
        cpus.put(cpu)
    lock = threading.Lock()

    def one(cell: str) -> tuple[str, dict | None]:
        cpu = cpus.get()
        try:
            return cell, measure(arguments.binary, cell, cpu, arguments)
        finally:
            cpus.put(cpu)

    with concurrent.futures.ThreadPoolExecutor(max_workers=cpus.qsize()) as pool:
        for done, (cell, ns) in enumerate(pool.map(one, wanted), 1):
            with lock:
                record_cell(results, path, cell, ns, prints, today, arguments.limit)
            shown = ("timed out" if ns is None else "failed: " + ns["failed"][-120:] if "failed" in ns
                     else ", ".join(f"{op} {value:.1f}" for op, value in ns.items()))
            print(f"[{done}/{len(wanted)}] {cell}: {shown} ns", flush=True)
    return 0


def record_cell(results: dict, path: Path, cell: str, ns: dict | None, prints: dict[str, str], today: str, limit: int) -> None:
    """Merges one cell's result in and writes the results."""
    entry = {"fingerprint": prints[container_of(cell)], "recorded": today}
    if ns is None:
        entry["timed_out"] = limit
    elif "failed" in ns:
        entry["failed"] = ns["failed"]
    else:
        entry["ns"] = ns
    results["cells"][cell] = entry
    results["cells"] = dict(sorted(results["cells"].items()))
    path.write_text(json.dumps(results, indent=1) + "\n")


def coverage(arguments: argparse.Namespace) -> int:
    """The binary registers exactly the cells requests.json lists."""
    listed = subprocess.run([str(arguments.binary), "--benchmark_list_tests"], check=True, capture_output=True, text=True)
    registered = {line.split("/iterations:")[0] for line in listed.stdout.splitlines() if line}
    wanted = set(cells())
    for name in sorted(wanted - registered):
        print(f"not registered: {name}")
    for name in sorted(registered - wanted):
        print(f"registered, but no choice reads it: {name}")
    return 0 if registered == wanted else 1


def scale(quantity: str) -> str:
    """Which quantity a cost grows in, for comparing: the elements, the key range and the capacity are one (urd::scale_of)."""
    return complexity()["scales"][quantity]


def costs() -> dict[str, dict]:
    """Each container's entry of complexity.json, by id."""
    return {each["representation"]: each for each in complexity()["representations"]}


def cost(table: dict[str, dict], container: str, operation: str, part: str | None = None) -> dict | None:
    """The cost of an operation in a container, a wrapper's passed-on one resolved to its part's: the part it wraps for
    the request (benchmarks/requests.json; one id may wrap different parts), else complexity.json's."""
    entry = table.get(container, {}).get("costs", {}).get(operation)
    if entry and entry.get("as_part"):
        return cost(table, part or table[container].get("part", ""), operation)
    return entry


def classify(table: dict[str, dict], chosen: dict, other: dict, operations: list[str], small: bool) -> str:
    """settled, wrong_order or measure, from the two servers' costs on the operations (each server as
    requests.json gives it: its container, the part it wraps for the request, its words per element)."""
    chosen_better = other_better = apart = False
    for operation in operations:
        a = cost(table, chosen["container"], operation, chosen.get("part"))
        b = cost(table, other["container"], operation, other.get("part"))
        if not a or not b:
            continue
        order = complexity()["growths"]
        ga, gb = order.index(a["growth"]), order.index(b["growth"])
        # O(1) is below any growth in any quantity; O(n changes) above any growth up to linear in the elements;
        # other growths compare only within one quantity.
        if a["growth"] == "one" and b["growth"] != "one":
            chosen_better = True
        elif b["growth"] == "one" and a["growth"] != "one":
            other_better = True
        elif b["growth"] == "n_times" and scale(a["in"]) == "n" and ga <= order.index("linear"):
            chosen_better = True
        elif a["growth"] == "n_times" and scale(b["in"]) == "n" and gb <= order.index("linear"):
            other_better = True
        elif scale(a["in"]) != scale(b["in"]):
            apart = True
        elif ga < gb:
            chosen_better = True
        elif gb < ga:
            other_better = True
    # The other wraps the chosen one (a change log, a layer): it does its work and more.
    if other.get("part") == chosen["container"] and apart and not other_better:
        apart, chosen_better = False, True
    if small or apart or (chosen_better and other_better):
        return "measure"
    if chosen_better:
        return "settled"
    if other_better:
        return "measure" if chosen["words"] < other["words"] else "wrong_order"
    return "measure"


def comparisons() -> dict[str, dict]:
    """The registry's claims, merged: "chosen > other / operations / shape[ / small]" -> the claim and its requests."""
    table = costs()
    result: dict[str, dict] = {}
    for row in requests()["requests"]:
        if not row["serving"]:
            continue
        chosen, *others = row["serving"]
        suffix = f" / {','.join(row['operations'])} / {row['shape']}" + (" / small" if row["small"] else "")
        experiment = row["shape"] + ("/small" if row["small"] else "")
        for other in others:
            key = f"{chosen['container']} > {other['container']}{suffix}"
            if key not in result:
                fair = set(other.get("uninvited", [])) <= set(chosen.get("uninvited", []))
                result[key] = {"chosen": chosen["container"], "other": other["container"], "operations": row["operations"],
                               "experiment": experiment,
                               "outcome": classify(table, chosen, other, row["operations"], row["small"]) if fair else "uninvited",
                               "requests": []}
            result[key]["requests"].append(row["request"])
    return result


def claim_failures(found: dict[str, dict]) -> list[str]:
    """Claims the costs refute, and measured claims whose operations an experiment does not time."""
    experiments = requests()["experiments"]
    failures = []
    for key, claim in found.items():
        if claim["outcome"] == "wrong_order":
            failures.append(f"{key}: {claim['other']} grows slower and takes no more memory (share/urd/complexity.json); "
                            f"reorder the registry, or correct the costs ({claim['requests'][0]})")
        if claim["outcome"] == "measure":
            for container in (claim["chosen"], claim["other"]):
                if experiment_for(experiments, container, claim) is None:
                    failures.append(f"{key}: no experiment of {container} on {claim['experiment']} times {', '.join(claim['operations'])}")
    return failures


def experiment_for(experiments: dict[str, dict], container: str, claim: dict) -> str | None:
    """The experiment of a container on a claim's shape that times all the claim's operations ("#2" and on included)."""
    base = f"{container}/{claim['experiment']}"
    for name, experiment in experiments.items():
        if (name == base or name.startswith(base + "#")) and all(op in experiment["operations"] for op in claim["operations"]):
            return name
    return None


def verdicts(results: dict, found: dict[str, dict]) -> tuple[list[str], list[str]]:
    """The measured claims that fail, and those that lose at a smaller size only: by the time of a lifecycle (the sum
    of the compared operations' times per element), decided at the largest size both containers were measured at."""
    experiments = requests()["experiments"]
    failed, smaller = [], []
    for key, claim in found.items():
        if claim["outcome"] != "measure":
            continue
        mine_at = experiment_for(experiments, claim["chosen"], claim)
        theirs_at = experiment_for(experiments, claim["other"], claim)
        if mine_at is None or theirs_at is None:
            continue  # claim_failures names it
        totals = {}
        for name, result in results["cells"].items():
            if not name.startswith(f"{mine_at}/") or "ns" not in result:
                continue
            size = int(name.rsplit("/", 1)[1])
            theirs = results["cells"].get(f"{theirs_at}/{size}", {}).get("ns")
            if theirs:
                totals[size] = (sum(result["ns"].get(op, 0) for op in claim["operations"]), sum(theirs.get(op, 0) for op in claim["operations"]))
        largest = max(totals, default=None)
        for size, (mine, other) in sorted(totals.items()):
            if mine > other + max(other * TOLERANCE, FLOOR):
                line = f"{key}: at {size}, {mine:.1f} against {other:.1f} ns per element ({claim['requests'][0]})"
                (failed if size == largest else smaller).append(line)
    return failed, smaller


def growth_failures(results: dict) -> list[str]:
    """Measured times that grow faster than their declared cost from the smallest size to the largest: a cost is an
    upper bound, so only growing faster refutes it (with a factor of ten for caches). Read on cheap elements only:
    the costs are for elements that are cheap to copy and destroy (a Store of Stores destroys each on clear), and on
    sizes that count elements (a pool's sizes are row lengths)."""
    table = costs()
    experiments = requests()["experiments"]
    times: dict[tuple[str, str], dict[int, float]] = {}
    for name, result in results["cells"].items():
        experiment = name.rsplit("/", 1)[0]
        if "ns" not in result or "/small" in experiment or not experiments.get(experiment, {}).get("cheap"):
            continue
        if any(op in experiments.get(experiment, {}).get("operations", []) for op in ("insert_row", "find_row")):
            continue
        container, size = container_of(name), int(name.rsplit("/", 1)[1])
        for operation, ns in result["ns"].items():
            # The time of one call: per element times the elements it ran over (iterate, clear), else per call.
            times.setdefault((name.rsplit("/", 1)[0], operation), {})[size] = ns * (size if operation in ("clear", "iterate") else 1)
    failures = []
    for (experiment, operation), by_size in sorted(times.items()):
        how = cost(table, container_of(experiment), operation)
        if not how or how["in"] not in ("n", "keys", "capacity", "changes") or len(by_size) < 2:
            continue
        smallest, largest = min(by_size), max(by_size)
        ratio, grown = by_size[largest] / max(by_size[smallest], 1e-3), largest / smallest
        allowed = {"one": 1, "log": math.log(largest) / math.log(smallest), "linear": grown, "n_log_n": grown * math.log(largest) / math.log(smallest),
                   "n_times": grown * grown}[how["growth"]]
        if ratio > 10 * allowed:
            failures.append(f"{experiment} {operation}: declared {how['cost']}, time grew {ratio:.0f}x from {smallest} to {largest}")
    return failures


def quadratic_cells(results: dict) -> tuple[dict[str, str], list[str]]:
    """The cells whose container declares an operation O(n changes), quadratic over a run of n changes, and those of
    them that ran past the limit: reported as known, not failed."""
    table = costs()
    experiments = requests()["experiments"]
    known = {}
    for name in results["cells"]:
        experiment = experiments.get(name.rsplit("/", 1)[0], {})
        quadratic = [f"{op} {cost(table, experiment['container'], op)['cost']}" for op in experiment.get("operations", [])
                     if (cost(table, experiment["container"], op) or {}).get("growth") == "n_times"]
        if quadratic:
            known[name] = ", ".join(quadratic)
    return known, sorted(name for name in known if "timed_out" in results["cells"][name])


def check(arguments: argparse.Namespace) -> int:
    """Every claim consistent with the costs; every cell measured and current; every measured claim holding; every
    measured time within its declared cost."""
    found = comparisons()
    failures = claim_failures(found)
    for line in failures:
        print(f"claim: {line}")
    path = results_path(arguments.machine) if arguments.machine else next(iter(sorted(RESULTS.glob("*.json"))), None)
    if path is None or not path.exists():
        print("no results: run benchmarks/record.py record")
        return 1
    results = load_results(path)
    missing = stale_or_missing(results, fingerprints())
    failed, smaller = verdicts(results, found)
    slow = growth_failures(results)
    known, slow_cells = quadratic_cells(results)
    slow += [f"{name}: ran past {result['timed_out']} s" for name, result in results["cells"].items() if "timed_out" in result and name not in known]
    slow += [f"{name}: failed ({result['failed'][-120:]})" for name, result in results["cells"].items() if "failed" in result]
    for name in missing:
        print(f"stale or missing: {name}")
    for line in failed:
        print(f"choice fails: {line}")
    for line in slow:
        print(f"cost: {line}")
    if missing:
        print(f"{len(missing)} cells to measure: benchmarks/record.py record --binary <build>/benchmark_comparisons")
    for name in slow_cells:
        print(f"known: {name} ran past the limit; a declared cost is quadratic over its run ({known[name]})")
    print(f"{path.name}: {len(results['cells'])} cells, {len(found)} claims, {len(failed)} failing, {len(smaller)} slower at a smaller size only")
    return 1 if failures or missing or failed or slow else 0


def doc_block(results: dict, path: Path) -> str:
    """The generated part of BENCHMARKS.md: the summary, then the exceptions."""
    found = comparisons()
    failed, smaller = verdicts(results, found)
    outcomes: dict[str, int] = {}
    for claim in found.values():
        outcomes[claim["outcome"]] = outcomes.get(claim["outcome"], 0) + 1
    context = results.get("context", {})
    lines = [BEGIN, "", "## The registry's choices, measured", "",
             f"Generated from `benchmarks/results/{path.name}` ({context.get('cpu')}, {results.get('compiler')}). "
             "Each container is measured on its own (`benchmarks/requests.json`): its lifecycle on each shape of element "
             "at three sizes, the median of three runs, in ns per operation. For each request, the chosen container "
             "against every other that serves it: "
             f"{outcomes.get('uninvited', 0)} not compared, as the other gives a costly guarantee the request did not ask "
             f"for; {outcomes.get('settled', 0)} settled by their costs; {outcomes.get('measure', 0)} measured. "
             "Alike costs are decided asymptotically: a measured choice holds where, at the largest size measured, the chosen "
             "container's lifecycle (the sum of the compared operations' times per element) exceeds the other's by at most "
             f"{TOLERANCE:.0%} or {FLOOR:.0f} ns, whichever is larger. The costs and measured times of every container are "
             "in the complexity tables of each kind of Store.", ""]
    lines += ["### Choices that fail", ""]
    lines += [f"- {line}" for line in failed] or ["None."]
    lines += ["", "### Slower at a smaller size only", ""]
    lines += [f"- {line}" for line in smaller] or ["None."]
    return "\n".join([*lines, "", END])


def doc(arguments: argparse.Namespace) -> int:
    """Writes the generated block of BENCHMARKS.md, or checks it is current."""
    path = next(iter(sorted(RESULTS.glob("*.json"))), None)
    if path is None:
        print("no results: run benchmarks/record.py record")
        return 1
    text = DOC.read_text()
    block = doc_block(load_results(path), path)
    if BEGIN in text:
        written = text[: text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    else:
        written = text.rstrip("\n") + "\n\n" + block + "\n"
    if arguments.check:
        if written != text:
            print(f"{DOC.relative_to(ROOT)} is out of date: benchmarks/record.py doc")
            return 1
        return 0
    DOC.write_text(written)
    return 0


def main() -> int:
    """The command line."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    to_record = commands.add_parser("record")
    to_record.add_argument("--binary", type=Path, required=True)
    to_record.add_argument("--all", action="store_true")
    to_record.add_argument("--min-time", default="0.1s")
    to_record.add_argument("--cpu", help="pin to these CPUs, one cell on each at a time (taskset): 2 or 2,4,6")
    to_record.add_argument("--compiler", default="unknown")
    to_record.add_argument("--machine")
    to_record.add_argument("--limit", type=int, default=120, help="seconds a cell may run")
    to_cover = commands.add_parser("coverage")
    to_cover.add_argument("--binary", type=Path, required=True)
    to_check = commands.add_parser("check")
    to_check.add_argument("--machine")
    to_doc = commands.add_parser("doc")
    to_doc.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    return {"record": record, "coverage": coverage, "check": check, "doc": doc}[arguments.command](arguments)


if __name__ == "__main__":
    sys.exit(main())
